/* tiny stack-less VM: single 8-bit accumulator, bytecode in .rdata */
static int vm_run(const unsigned char *code, int codelen, const char *in)
{
    unsigned int r = 0;
    int pc = 0, pos = 0, n = (int)strlen(in);
    unsigned char op, imm;

    while (pc < codelen) {
        op = code[pc++];
        switch (op) {
        case 0x00:                       /* halt, fail */
            return 0;
        case 0x01:                       /* halt, ok */
            return 1;
        case 0x02:                       /* ld  imm          r = imm */
            r = code[pc++];
            break;
        case 0x03:                       /* xor imm */
            r ^= code[pc++];
            break;
        case 0x04:                       /* add imm */
            r = (r + code[pc++]) & 0xff;
            break;
        case 0x05:                       /* sub imm */
            r = (r - code[pc++]) & 0xff;
            break;
        case 0x06:                       /* mul imm */
            r = (r * code[pc++]) & 0xff;
            break;
        case 0x07:                       /* rol imm */
            imm = code[pc++] & 7;
            r = ((r << imm) | (r >> (8 - imm))) & 0xff;
            break;
        case 0x08:                       /* ror imm */
            imm = code[pc++] & 7;
            r = ((r >> imm) | (r << (8 - imm))) & 0xff;
            break;
        case 0x09:                       /* cmp in[pos], pos++ */
            if (pos >= n || (unsigned char)in[pos] != (unsigned char)r)
                return 0;
            pos++;
            break;
        case 0x0a:                       /* jmp rel8 */
            imm = code[pc++];
            pc += (imm < 0x80) ? imm : (int)imm - 256;
            break;
        case 0x0b:                       /* jz  rel8 */
            imm = code[pc++];
            if ((r & 0xff) == 0)
                pc += (imm < 0x80) ? imm : (int)imm - 256;
            break;
        case 0x0c:                       /* cmp length */
            if (n != code[pc++])
                return 0;
            break;
        case 0x0d:                       /* not */
            r = (~r) & 0xff;
            break;
        default:
            return 0;
        }
    }
    return 0;
}

