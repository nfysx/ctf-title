#include <stdio.h>
#include <string.h>

#define LEN 36
#define MUL 107
#define ADD 17
#define ROL 3

unsigned char PERM[36] = {
    0x0a, 0x19, 0x17, 0x1c, 0x02, 0x1b, 0x09, 0x11, 0x1d, 0x1f, 0x18, 0x1a,
    0x01, 0x12, 0x04, 0x21, 0x13, 0x07, 0x15, 0x1e, 0x0d, 0x06, 0x10, 0x03,
    0x23, 0x05, 0x00, 0x20, 0x0b, 0x0e, 0x14, 0x22, 0x08, 0x16, 0x0c, 0x0f,
};

unsigned char T[36] = {
    0x43, 0x4a, 0x98, 0x69, 0x1a, 0xe6, 0x37, 0x4a, 0x82, 0x47, 0x10, 0x52,
    0x08, 0x40, 0xbd, 0xc4, 0xc8, 0x0b, 0xa0, 0x3e, 0x6c, 0x33, 0x61, 0xa3,
    0x4d, 0xcc, 0x7b, 0xcb, 0xa8, 0xad, 0x37, 0x14, 0x9d, 0x05, 0x0e, 0xa3,
};

static int check(const char *in)
{
    unsigned char a[LEN], b[LEN], t[LEN];
    int i, n = (int)strlen(in);

    if (n != LEN)
        return 0;
    for (i = 0; i < LEN; i++)
        a[i] = (unsigned char)(in[i] ^ 0xa7);
    for (i = 0; i < LEN; i++)
        b[PERM[i]] = a[i];
    for (i = 0; i < LEN; i++)
        t[i] = (unsigned char)(((b[i] * MUL + i * 7 + ADD) & 0xff) << ROL
                               | ((b[i] * MUL + i * 7 + ADD) & 0xff) >> (8 - ROL));
    return memcmp(t, T, LEN) == 0;
}

int main(void)
{
    char buf[128];

    printf("input your flag: ");
    fflush(stdout);
    if (scanf("%127s", buf) != 1)
        return 1;
    if (check(buf)) {
        puts("Good!");
        return 0;
    }
    puts("Wrong!");
    return 1;
}
